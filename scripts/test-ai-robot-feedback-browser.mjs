import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--use-angle=swiftshader','--disable-gpu-sandbox']});
try{
 const page=await browser.newPage({viewport:{width:1180,height:820}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const response=await page.goto('http://localhost:3000/dev/characters',{waitUntil:'domcontentloaded',timeout:20000});
 assert.equal(response?.status(),200);
 await page.getByRole('status').getByText('3D model loaded').waitFor({timeout:20000});
 const events=page.getByRole('group',{name:'Game reaction events'});
 await events.getByRole('button',{name:'Doğru cevap'}).click();
 await page.getByText('Aferin!',{exact:true}).waitFor({timeout:3000});
 assert.match(await page.locator('.dv-ai-robot-preview__output').innerText(),/happy/);
 await page.waitForTimeout(1900);
 assert.match(await page.locator('.dv-ai-robot-preview__output').innerText(),/idle/);
 await events.getByRole('button',{name:'Görev tamamlandı'}).click();
 await page.getByText('Harika!',{exact:true}).waitFor({timeout:3000});
 await events.getByRole('button',{name:'Tekrar dene'}).click();
 assert.equal(await page.locator('.dv-mascot-bubble').innerText(),'Harika!');
 assert.match(await page.locator('.dv-ai-robot-preview__output').innerText(),/celebrate/);
 await page.getByLabel('Message language').selectOption('en');
 assert.equal(await page.locator('.dv-mascot-bubble').innerText(),'Amazing!');
 await page.waitForTimeout(3300);
 assert.equal(await page.locator('.dv-mascot-bubble').count(),0);
 assert.match(await page.locator('.dv-ai-robot-preview__output').innerText(),/idle/);
 await events.getByRole('button',{name:'Correct answer'}).click();
 assert.equal(await page.locator('.dv-mascot-bubble').innerText(),'Well done!');
 await page.screenshot({path:'reports/visual/ai-robot-feedback.png',fullPage:true});
 // Eye and antenna mood lighting is driven by the original GLB materials.
 await page.getByRole('group',{name:'Robot animation actions'}).getByRole('button',{name:'idle'}).click();
 const expression=page.getByLabel('Expression preset');
 await expression.selectOption('happy');
 await page.waitForTimeout(450);
 const bright=await page.locator('.dv-ai-robot-preview__frame').screenshot({path:'reports/visual/ai-robot-mood-happy.png'});
 await expression.selectOption('sleepy');
 await page.waitForTimeout(450);
 const dim=await page.locator('.dv-ai-robot-preview__frame').screenshot({path:'reports/visual/ai-robot-mood-sleepy.png'});
 assert.equal(bright.equals(dim),false,'Sleepy eyes and antenna should differ visibly from happy mood');
 await expression.selectOption('surprised');
 await page.waitForTimeout(350);
 const surprised=await page.locator('.dv-ai-robot-preview__frame').screenshot({path:'reports/visual/ai-robot-mood-surprised.png'});
 assert.equal(surprised.equals(dim),false,'Surprised must render different eye shape from sleepy');
 assert.equal(surprised.equals(bright),false,'Surprised must render different eye shape from happy');
 await page.getByRole('group',{name:'Robot animation actions'}).getByRole('button',{name:'blink'}).click();
 await page.waitForTimeout(165);
 const blink=await page.locator('.dv-ai-robot-preview__frame').screenshot({path:'reports/visual/ai-robot-eye-blink.png'});
 assert.equal(blink.equals(surprised),false,'Blink must visibly close eyes');
 await page.getByRole('group',{name:'Robot animation actions'}).getByRole('button',{name:'idle'}).click();
 await expression.selectOption('thinking');
 await page.waitForTimeout(380);
 await page.locator('.dv-ai-robot-preview__frame').screenshot({path:'reports/visual/ai-robot-mood-thinking.png'});
 // Real-model body-language regression: wheels, bounce, celebration are distinct.
 const motion=page.getByRole('group',{name:'Robot animation actions'});
 await motion.getByRole('button',{name:'idle',exact:true}).click();
 await page.waitForTimeout(320);
 const motionIdle=await page.locator('.dv-ai-robot-preview__frame').screenshot({path:'reports/visual/ai-robot-motion-idle.png'});
 await motion.getByRole('button',{name:'walk',exact:true}).click();
 await page.waitForTimeout(380);
 const motionRoll=await page.locator('.dv-ai-robot-preview__frame').screenshot({path:'reports/visual/ai-robot-motion-roll.png'});
 await motion.getByRole('button',{name:'happy',exact:true}).click();
 await page.waitForTimeout(410);
 const motionHappy=await page.locator('.dv-ai-robot-preview__frame').screenshot({path:'reports/visual/ai-robot-motion-happy.png'});
 await motion.getByRole('button',{name:'celebrate',exact:true}).click();
 await page.waitForTimeout(480);
 const motionCelebrate=await page.locator('.dv-ai-robot-preview__frame').screenshot({path:'reports/visual/ai-robot-motion-celebrate.png'});
 assert.equal(motionIdle.equals(motionRoll),false,'roll must differ from idle');
 assert.equal(motionRoll.equals(motionHappy),false,'roll must differ from happy');
 assert.equal(motionHappy.equals(motionCelebrate),false,'celebrate must differ from happy');
 await motion.getByRole('button',{name:'idle',exact:true}).click();
 await page.waitForTimeout(700);
 assert.match(await page.locator('.dv-ai-robot-preview__output').innerText(),/idle/);
 assert.deepEqual(errors,[]);
 console.log('AI_ROBOT_FEEDBACK_BROWSER_PASS: bundled GLB, TR/EN messages, priority, expiry/idle, facial expressions plus distinct roll/happy/celebrate body motion');
}finally{await browser.close()}
